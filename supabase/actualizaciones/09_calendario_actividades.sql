-- V4.6 - CALENDARIO DE ACTIVIDADES
-- Añade exclusivamente una tabla de agenda. No modifica semovientes,
-- controles sanitarios, reproducción, bajas, movimientos ni sus políticas.
-- Antes de ejecutar, realizar respaldo y, de ser posible, probar en copia de desarrollo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.calendario_actividades (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unidad_id bigint NOT NULL REFERENCES public.unidades_operativas(id) ON DELETE RESTRICT,
  titulo text NOT NULL CHECK (length(btrim(titulo)) BETWEEN 5 AND 120),
  tipo text NOT NULL CHECK (tipo IN (
    'vacunacion','desparasitacion','control_sanitario','movimiento',
    'reproduccion','inventario','inspeccion','otra'
  )),
  fecha date NOT NULL,
  hora time WITHOUT time zone,
  descripcion text NOT NULL DEFAULT '' CHECK (length(descripcion) <= 2000),
  codigo_semoviente varchar(80), -- referencia opcional; NO modifica ni vincula automáticamente al animal
  prioridad text NOT NULL DEFAULT 'normal' CHECK (prioridad IN ('normal','alta')),
  estado text NOT NULL DEFAULT 'programada' CHECK (estado IN ('programada','realizada','cancelada')),
  creado_por uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id),
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_por uuid DEFAULT auth.uid() REFERENCES auth.users(id)
);

CREATE INDEX IF NOT EXISTS calendario_actividades_unidad_fecha_idx
  ON public.calendario_actividades(unidad_id, fecha);
CREATE INDEX IF NOT EXISTS calendario_actividades_fecha_idx
  ON public.calendario_actividades(fecha);

ALTER TABLE public.calendario_actividades ENABLE ROW LEVEL SECURITY;

-- Lectura: cada usuario solo observa las unidades autorizadas por los controles institucionales.
DROP POLICY IF EXISTS calendario_v46_leer ON public.calendario_actividades;
CREATE POLICY calendario_v46_leer ON public.calendario_actividades
FOR SELECT TO authenticated
USING (
  private.rb_rol_actual() IN ('SUP_DEPTO_VII','JEFE_DIV_B','RESP_UNIDAD')
  AND private.rb_puede_consultar_unidad(unidad_id)
);

-- Creación: supervisor en unidades autorizadas; responsable únicamente en su unidad.
DROP POLICY IF EXISTS calendario_v46_crear ON public.calendario_actividades;
CREATE POLICY calendario_v46_crear ON public.calendario_actividades
FOR INSERT TO authenticated
WITH CHECK (
  creado_por = auth.uid()
  AND (
    (private.rb_rol_actual() = 'SUP_DEPTO_VII'
      AND private.rb_puede_consultar_unidad(unidad_id))
    OR
    (private.rb_rol_actual() = 'RESP_UNIDAD'
      AND unidad_id = private.rb_unidad_actual())
  )
);

-- Edición: supervisor, o responsable autor de la actividad en su propia unidad.
DROP POLICY IF EXISTS calendario_v46_editar ON public.calendario_actividades;
CREATE POLICY calendario_v46_editar ON public.calendario_actividades
FOR UPDATE TO authenticated
USING (
  (private.rb_rol_actual() = 'SUP_DEPTO_VII'
    AND private.rb_puede_consultar_unidad(unidad_id))
  OR
  (private.rb_rol_actual() = 'RESP_UNIDAD'
    AND unidad_id = private.rb_unidad_actual()
    AND creado_por = auth.uid())
)
WITH CHECK (
  (private.rb_rol_actual() = 'SUP_DEPTO_VII'
    AND private.rb_puede_consultar_unidad(unidad_id))
  OR
  (private.rb_rol_actual() = 'RESP_UNIDAD'
    AND unidad_id = private.rb_unidad_actual()
    AND creado_por = auth.uid())
);

-- No se autoriza borrado directo: las actividades se cancelan, preservando su registro.
REVOKE ALL ON public.calendario_actividades FROM anon;
REVOKE DELETE ON public.calendario_actividades FROM authenticated;
GRANT SELECT, INSERT, UPDATE ON public.calendario_actividades TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.calendario_actividades_id_seq TO authenticated;

COMMIT;

